"""语义净化的提示模板（论文 §4.1 的四类无关语义范畴）。

提示词里同时写了两件事：

1. **要剥离什么**：时空信息 / 专有实体 / 过程性描述 / 冗余修饰；
2. **必须保留什么**："什么对象 + 出现了什么缺陷/偏差"，以及极性词。

第 2 条是硬约束而非建议：实测表明 Qwen3.8-27B 会把
``焊机二维码上名称与系统不一致`` 净化成 ``焊机二维码名称与系统一致``（见陷阱 P1），
即使提示词写了硬约束、并给出完全相同的少样本示例仍会复现。因此提示词只是
"第一道防线"，真正的保证来自 ``guard.polarity_preserved`` 的确定性校验。
"""

from __future__ import annotations

SYSTEM_PROMPT = (
    "你是工程质量巡检文本的语义净化器。你的唯一任务是从一条偏差记录中剥离与"
    "问题类别判别无关的语义成分，输出只保留核心问题描述的最简文本。"
    "你不判断问题属于哪一类，只做剥离与压缩。"
)

#: 四类无关语义范畴（论文 §4.1）。
NOISE_SPEC = """需要剥离的四类无关语义成分：
1. 时空信息：具体日期、厂房编号、区域名称、方位描述、标高、轴线、桩号、段落号。
2. 专有实体：公司名称、人员姓名、工程/设备/材料编号、图纸号、规范号、测量报告号。
3. 过程性描述：如"巡检时发现""日常检查发现""验收时发现""查看…时发现"等模板化引导语。
4. 冗余修饰：程度副词、范畴限定语、对规范条文的整段引用、以及"已通知班组处理""已整改"等处置性尾巴。

必须保留：描述问题本身的主谓宾，即"什么对象 + 出现了什么缺陷/偏差"。

【最高优先级的硬约束】
绝对不得改变问题的语义极性：否定词、程度与方向必须原样保留。
"不一致""不符合""未及时""未清理""不牢靠""无法识别""超过""不足"等表述必须完整保留，
绝不能改写为"一致""符合""已清理""牢靠""可识别"等肯定形式。
净化只做删减，不做改写；宁可少删，也不得改变意思。"""

#: 少样本示例：覆盖四类噪声与三种"极性必须保留"的写法。
FEWSHOT: list[tuple[str, str]] = [
    ("11 轴线东侧堆场钢筋拐头与地面接触", "钢筋拐头触地"),
    ("1C16 段模板龙骨间距过大", "模板龙骨间距过大"),
    (
        "20250810 在B9 库检查过程中发现5BFX20ST0073 支架焊接区域根部存在锈迹，"
        "不满足“待焊表面应无水、无油脂、无氧化物”的要求；已通知班组进行打磨处理。已处理",
        "支架焊接区锈迹未处理",
    ),
    ("2025.11.11 管道三维图版本错误", "图纸版本错误"),
    (
        "2025 年12 月17 日，中交四航提交的北护岸直立段基槽开挖验收水深测量报告，"
        "测量示意图缺少测量范围边界坐标",
        "测量示意图缺少边界坐标",
    ),
    ("14-1 连续段凿毛不到位", "凿毛不到位"),
    (
        "2025.11.03 在工艺评定车间巡检发现焊机二维码上名称与系统不一致，已要求更换二维码标签",
        "焊机二维码名称与系统不一致",
    ),
    (
        "2025.10.16，QC1 巡查不锈钢车间发现已用鞋套未及时回收。",
        "已用鞋套未及时回收",
    ),
]


def build_prompt(text: str) -> str:
    """把一条原文包装成单轮指令。

    统一走文本通道（不使用 VL 的图像分支），因此这里只构造纯文本提示；
    调用方负责套 chat template。
    """

    shots = "\n".join(f"输入：{source}\n输出：{target}" for source, target in FEWSHOT)
    return (
        f"{NOISE_SPEC}\n\n"
        f"输出要求：只输出净化后的文本本身，不要解释、不要引号、不要标点之外的任何内容，"
        f"长度尽量控制在 20 个汉字以内。若原文已无噪声，则原样输出核心语义。\n\n"
        f"示例：\n{shots}\n\n"
        f"输入：{text}\n输出："
    )


__all__ = ["FEWSHOT", "NOISE_SPEC", "SYSTEM_PROMPT", "build_prompt"]
